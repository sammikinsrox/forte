"""Each note's loudness, voiced even against a reference (issue 0022 §6): a level per note, in dB,
added to its whole output (strings, tail, knock, phantoms), so its strike and early ring are as
loud against its neighbours as in the reference. Keyscape's strikes sit within ±2.5 dB of C4's
from C2 to C6; Forte's treble came out 12-15 dB short, and its board made neighbours jump by 4-10.

    python tools/fitting/fit_level.py fit <reference_sweep.wav> <forte_sweep.wav>   → data/model/level.json
    python tools/fitting/fit_level.py build                                          → engine/src/LevelFit.inc

Sweeps of make_note_sweep.py's schedule (3 s holds). Per note at velocities 64 and 96 (127 clips
in Keyscape, 32 is near its noise): loudness = the mean of the strike's peak (first 50 ms) and the
0.1-0.5 s rms, each of the channels' rms envelope, in dB. The correction is the reference's
loudness minus Forte's, the two velocities' mean, made level-neutral over the keyboard (median 0),
limited to LIMIT_DB, and added to the level already committed (fit against a sweep rendered with
it), so passes converge.
"""

import argparse
import json
import sys

import numpy as np

import forte_audio as fa
from fit_hammer import _round, _write_json, ROOT

PARAMETERS = ROOT / "data" / "model" / "level.json"
TABLE = ROOT / "engine" / "src" / "LevelFit.inc"
VELOCITIES = (64, 96)
LIMIT_DB = 18.0
HOLD, GAP, LEAD_IN = 3.0, 2.0, 2.0


def loudness(path):
    x, rate = fa.read_wav(path)
    sched, t = [], LEAD_IN
    for m in range(21, 109):
        for v in (32, 64, 96, 127):
            sched.append((t, m, v)); t += HOLD + GAP
    strikes = fa.find_strikes(x, rate, [s for s, _, _ in sched])
    out = {}
    for (s, m, v), st in zip(sched, strikes):
        if st is None or v not in VELOCITIES:
            continue
        e = fa.envelope_signal(x[int(st * rate): int((st + 0.6) * rate)])
        peak = 20 * np.log10(e[: int(0.05 * rate)].max() + 1e-12)
        body = 10 * np.log10(np.mean(e[int(0.1 * rate): int(0.5 * rate)] ** 2) + 1e-24)
        out[(m, v)] = 0.5 * (peak + body)
    return out


def committed():
    if PARAMETERS.exists():
        return {int(k): v for k, v in json.loads(PARAMETERS.read_text())["levelDb"].items()}
    return {m: 0.0 for m in range(21, 109)}


def fit(args):
    ref, forte = loudness(args.reference), loudness(args.forte)
    diff = {}
    for m in range(21, 109):
        d = [ref[(m, v)] - forte[(m, v)] for v in VELOCITIES if (m, v) in ref and (m, v) in forte]
        if d:
            diff[m] = float(np.mean(d))
    neutral = float(np.median(list(diff.values())))
    old = committed()
    levels = {}
    for m in range(21, 109):
        correction = diff.get(m, neutral) - neutral
        levels[m] = float(np.clip(old.get(m, 0.0) + correction, -LIMIT_DB, LIMIT_DB))
    _write_json(PARAMETERS, {
        "about": "Each note's level (dB, on its whole output), voiced even against the user's Keyscape sweep "
                 "(tools/fitting/fit_level.py; issue 0022 §6): strike peak and 0.1-0.5 s rms, velocities 64 and 96, "
                 "level-neutral over the keyboard.",
        "levelDb": {str(m): _round(levels[m]) for m in range(21, 109)},
    })
    for lo in range(21, 109, 12):
        print(" ".join(f"{fa.note_name(m):>4s}{levels[m]:+5.1f}" for m in range(lo, min(lo + 12, 109))))


def build(_args):
    data = json.loads(PARAMETERS.read_text())["levelDb"]
    lines = ["// Generated by tools/fitting/fit_level.py build from data/model/level.json. Don't edit.",
             "// Each note's level, dB, A0 to C8"]
    values = [float(data[str(m)]) for m in range(21, 109)]
    for i in range(0, len(values), 12):
        lines.append(", ".join(repr(v) for v in values[i: i + 12]) + ",")
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLE.relative_to(ROOT)}")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("step", choices=["fit", "build"])
    parser.add_argument("reference", nargs="?")
    parser.add_argument("forte", nargs="?")
    args = parser.parse_args()
    if args.step == "fit":
        if not (args.reference and args.forte):
            sys.exit("fit needs the reference and Forte sweeps")
        fit(args)
    build(args)


if __name__ == "__main__":
    main()
