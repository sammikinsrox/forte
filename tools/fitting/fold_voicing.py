"""Folds a voicing lab export into the committed voicing (SPEC §6.5, §3.2's voicing overrides).

    python tools/fitting/fold_voicing.py fold [<voicing.json>]   (default Documents/Forte/voicing.json)
    python tools/fitting/fold_voicing.py build                   (regenerates the .inc only)

The lab's values are relative to the voicing it ran on, so the fold asks the engine what they
mean (forte-render --lab-values: the engine's own mapping, one per note and per bridge region)
and puts that on top of what's committed:

- Hammer and string controls: data/model/voicing-overrides.json, one value per note and control
  on top of the fitted tables (hammer.json, decay.json and PianoModel.cpp's curves), so refitting
  those keeps the voicing. Multipliers multiply, feltSpike (ε) and velocityBrightness (the contact
  speed exponent) replace, overtoneDecay adds. Tape drive replaces the model's.
- Board: pickup (the direct path's gain, per region) and tilt replace the generator's settings in
  data/model/board.json; the colour shelves add to data/model/board-colour.json at its centres.
  make_seed_irs.py then writes the new IRs and their parts.

Each fold bumps the voicing revision. The export carries the revision it was made on, and the
fold refuses one from another revision (its 50s meant a different voicing). A project saved with
lab values from an older revision opens with every lab control back at 50, since the voicing it
moved is now the committed one.

After a fold, rebuild (Release) and run tools/lab-identity.ps1's renders by ear: the new 50s
should sound as the old build did with the export loaded (`forte-render --voicing`).
"""

import argparse
import datetime
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OVERRIDES = ROOT / "data" / "model" / "voicing-overrides.json"
BOARD = ROOT / "data" / "model" / "board.json"
COLOUR = ROOT / "data" / "model" / "board-colour.json"
INC = ROOT / "engine" / "src" / "VoicingOverrides.inc"
RENDER = ROOT / "build" / "tools" / "forte-render" / "forte_render_artefacts" / "Release" / "forte-render.exe"
DEFAULT_VOICING = Path.home() / "Documents" / "Forte" / "voicing.json"

FORMAT = "forte-voicing-overrides"
NOTES = range(21, 109)
REGIONS = ["bass", "tenor", "middle", "treble"]

# Each per-note lab control: the override it folds into, and how (SPEC §6.5's ranges).
NOTE_CONTROLS = {
    "feltHardness":       ("feltStiffnessScale", "scale"),
    "feltSpike":          ("feltRelaxation", "replace"),
    "velocityBrightness": ("contactSpeedExponent", "replace"),
    "strikePosition":     ("strikePositionScale", "scale"),
    "hammerMass":         ("hammerMassScale", "scale"),
    "knockLevel":         ("knockScale", "scale"),
    "inharmonicity":      ("inharmonicityScale", "scale"),
    "unisonSpread":       ("unisonSpreadScale", "scale"),
    "sustain":            ("sustainRateScale", "scale"),
    "overtoneDecay":      ("overtoneDecayExponent", "offset"),
    "secondStage":        ("aftersoundRateScale", "scale"),
    "phantomLevel":       ("phantomLevelScale", "scale"),
}
NEUTRAL = {"scale": 1.0, "offset": 0.0, "replace": None}  # None: the fitted value


def neutral_overrides():
    return {
        "format": FORMAT,
        "version": 1,
        "revision": 0,
        "folds": [],
        "tapeDrive": None,
        "notes": {field: [NEUTRAL[kind]] * len(NOTES) for field, kind in NOTE_CONTROLS.values()},
    }


def read_json(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def write_json(path, value):
    Path(path).write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8", newline="\n")


def c_double(x):
    return "-1.0" if x is None else repr(float(x))


def build():
    """engine/src/VoicingOverrides.inc from voicing-overrides.json."""
    o = read_json(OVERRIDES)
    if o.get("format") != FORMAT:
        sys.exit(f"{OVERRIDES}: not a voicing overrides file")
    fields = [field for field, _ in NOTE_CONTROLS.values()]
    lines = [
        "// Generated by tools/fitting/fold_voicing.py build from data/model/voicing-overrides.json. Don't edit.",
        f"inline constexpr int revision = {int(o['revision'])};",
        f"inline constexpr double tapeDrive = {c_double(o['tapeDrive'])};  // < 0: the model's own",
        "// midi, " + ", ".join(fields) + " (a replaced value < 0: the fitted one)",
        "inline constexpr NoteOverride notes[] {",
    ]
    for i, midi in enumerate(NOTES):
        values = ", ".join(c_double(o["notes"][field][i]) for field in fields)
        lines.append(f"    {{ {midi}, {values} }},")
    lines.append("};")
    INC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{INC.relative_to(ROOT)}: revision {o['revision']}")


def lab_values(voicing_path, render):
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "lab-values.json"
        subprocess.run([str(render), "--voicing", str(voicing_path), "--lab-values", str(out)], check=True)
        return read_json(out)


def compose(kind, old, new):
    if kind == "scale":
        return old * new
    if kind == "offset":
        return old + new
    return new


def fold(voicing_path, render, force):
    voicing = read_json(voicing_path)
    if voicing.get("format") != "forte-voicing":
        sys.exit(f"{voicing_path}: not a Forte voicing file")

    overrides = read_json(OVERRIDES)
    made_on = voicing.get("voicingRevision")
    if made_on != overrides["revision"] and not force:
        sys.exit(f"{voicing_path} was exported on voicing revision {made_on}, but the committed voicing is "
                 f"revision {overrides['revision']}: its 50s meant another voicing (--force folds it anyway)")

    values = lab_values(voicing_path, render)
    controls = voicing["controls"]

    def moved(control_id):
        v = controls.get(control_id, 50)
        return any(x != 50 for x in v.values()) if isinstance(v, dict) else v != 50

    changed = [c for c in controls if moved(c)]
    if not changed:
        sys.exit(f"{voicing_path}: every control is at 50, nothing to fold")

    # Hammer and strings, per note.
    for control_id, (field, kind) in NOTE_CONTROLS.items():
        if not moved(control_id):
            continue
        physical = values["notes"][control_id]
        current = overrides["notes"][field]
        overrides["notes"][field] = [compose(kind, current[i], physical[i]) if kind != "replace" else physical[i]
                                     for i in range(len(NOTES))]
    if moved("tapeDrive"):
        overrides["tapeDrive"] = values["tapeDrive"]

    # Board.
    board_moved = any(moved(c) for c in ("pickup", "boardTilt", "colourLow", "colourMid", "colourHigh"))
    if board_moved:
        board = read_json(BOARD)
        board["directGain"] = dict(zip(REGIONS, values["board"]["pickup"]))
        board["modeTiltDbPerOctave"] = values["board"]["tiltDbPerOctave"]
        write_json(BOARD, board)

        colour = read_json(COLOUR)
        for r, region in enumerate(REGIONS):
            add = values["board"]["colourDbAtCentres"][r]
            if len(add) != len(colour["centresHz"]):
                sys.exit("forte-render's colour centres don't match board-colour.json: rebuild it first")
            colour["regions"][region] = [round(g + a, 6) for g, a in zip(colour["regions"][region], add)]
        write_json(COLOUR, colour)

    overrides["revision"] += 1
    overrides["folds"].append({
        "revision": overrides["revision"],
        "folded": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
        "exported": voicing.get("exported"),
        "builtFrom": voicing.get("builtFrom"),
        "controls": {c: controls[c] for c in changed},
    })
    write_json(OVERRIDES, overrides)
    print(f"{OVERRIDES.relative_to(ROOT)}: folded {', '.join(changed)} as revision {overrides['revision']}")

    build()
    if board_moved:
        subprocess.run([sys.executable, str(ROOT / "tools" / "seed-irs" / "make_seed_irs.py")], check=True)
    print("Now rebuild (Release, with Reaper closed): the lab's 50s are the folded voicing.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    f = sub.add_parser("fold", help="fold an exported voicing into the committed one")
    f.add_argument("voicing", nargs="?", type=Path, default=DEFAULT_VOICING)
    f.add_argument("--render", type=Path, default=RENDER, help="the forte-render to ask (default: the Release build)")
    f.add_argument("--force", action="store_true", help="fold an export from another voicing revision")
    sub.add_parser("build", help="regenerate engine/src/VoicingOverrides.inc")
    sub.add_parser("init", help="write neutral overrides (revision 0), if there are none, and build")
    args = parser.parse_args()

    if args.command == "fold":
        fold(args.voicing, args.render, args.force)
    elif args.command == "init":
        if OVERRIDES.exists():
            sys.exit(f"{OVERRIDES.relative_to(ROOT)} exists; delete it first to start the voicing again")
        write_json(OVERRIDES, neutral_overrides())
        build()
    else:
        build()


if __name__ == "__main__":
    main()
