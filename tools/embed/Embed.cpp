// forte-embed: turns data files into a C++ source, so the engine can carry them without JUCE's
// BinaryData (SPEC §3.5: the model data is embedded in the binary).
//
//   forte-embed <output.cpp> <name>=<file> [<name>=<file>...]
//
// The output defines forte::detail::embeddedFiles() (engine/src/EmbeddedFiles.h). Each file is
// stored as 64-bit little-endian words, which MSVC compiles far faster than one literal per byte;
// the declared size is the file's exact byte count.

#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <vector>

namespace
{
struct Input
{
    std::string name;
    std::string path;
    std::vector<unsigned char> bytes;
};

bool readFile (const std::string& path, std::vector<unsigned char>& bytes)
{
    std::ifstream in (path, std::ios::binary);
    if (! in)
        return false;

    bytes.assign (std::istreambuf_iterator<char> (in), std::istreambuf_iterator<char>());
    return true;
}

std::string generate (const std::vector<Input>& inputs)
{
    std::ostringstream out;
    out << "// Generated by forte-embed. Do not edit.\n\n"
           "#include \"EmbeddedFiles.h\"\n\n"
           "#include <cstdint>\n\n"
           "namespace forte::detail\n{\nnamespace\n{\n";

    char word[24];

    for (std::size_t i = 0; i < inputs.size(); ++i)
    {
        const auto& bytes = inputs[i].bytes;
        const auto numWords = (bytes.size() + 7) / 8;
        out << "const std::uint64_t file" << i << "[] = {";

        for (std::size_t w = 0; w < numWords; ++w)
        {
            std::uint64_t value = 0;
            for (std::size_t b = 0; b < 8 && w * 8 + b < bytes.size(); ++b)
                value |= static_cast<std::uint64_t> (bytes[w * 8 + b]) << (8 * b);

            std::snprintf (word, sizeof word, "0x%llxu,", static_cast<unsigned long long> (value));
            out << (w % 8 == 0 ? "\n    " : "") << word;
        }

        out << (numWords == 0 ? "0u" : "") << "\n};\n\n";
    }

    out << "const EmbeddedFile files[] = {\n";
    for (std::size_t i = 0; i < inputs.size(); ++i)
        out << "    { \"" << inputs[i].name << "\", reinterpret_cast<const unsigned char*> (file" << i << "), "
            << inputs[i].bytes.size() << "u },\n";
    out << "};\n} // namespace\n\n"
           "std::span<const EmbeddedFile> embeddedFiles() noexcept\n{\n    return files;\n}\n"
           "} // namespace forte::detail\n";

    return out.str();
}
} // namespace

int main (int argc, char* argv[])
{
    if (argc < 3)
    {
        std::fprintf (stderr, "usage: forte-embed <output.cpp> <name>=<file> [<name>=<file>...]\n");
        return 2;
    }

    std::vector<Input> inputs;

    for (int i = 2; i < argc; ++i)
    {
        const std::string arg = argv[i];
        const auto equals = arg.find ('=');

        if (equals == std::string::npos || equals == 0)
        {
            std::fprintf (stderr, "forte-embed: expected <name>=<file>, got %s\n", arg.c_str());
            return 2;
        }

        Input input { arg.substr (0, equals), arg.substr (equals + 1), {} };

        if (! readFile (input.path, input.bytes))
        {
            std::fprintf (stderr, "forte-embed: can't read %s\n", input.path.c_str());
            return 1;
        }

        inputs.push_back (std::move (input));
    }

    std::ofstream out (argv[1], std::ios::binary);
    out << generate (inputs);
    return out ? 0 : 1;
}
